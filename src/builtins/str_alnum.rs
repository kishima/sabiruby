/// starts (`succ_alnum_run`).
pub fn run_of(cp: u32) -> (u32, u32) {
    if cp < MIN { return (0, 0); }
    let (mut lo, mut hi) = (0usize, RUNS.len());
    while hi - lo > 1 {
        let mid = (lo + hi) / 2;
        if RUNS[mid] >> MASK_BITS <= cp { lo = mid; } else { hi = mid; }
    }
    (RUNS[lo] & ((1 << MASK_BITS) - 1), RUNS[lo] >> MASK_BITS)
}
